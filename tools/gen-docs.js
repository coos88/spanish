#!/usr/bin/env node
// Generates chapters/N/{README,GRAMMAR,EXERCISES,VOCAB,PHRASES}.md from data/*.json so docs and app never drift.
// No dependencies: `node tools/gen-docs.js`
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const read = (f) => JSON.parse(fs.readFileSync(path.join(root, 'data', f), 'utf8'));
const esc = (s) => String(s).replace(/\|/g, '\\|');
const write = (rel, text) => { const p = path.join(root, rel); fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, text); };
const GEN = 'Generated by `node tools/gen-docs.js` from `data/*.json`. Don\'t edit by hand.';

const base = { vocab: read('vocab.json'), phrases: read('phrases.json') };
const chapters = fs.readdirSync(path.join(root, 'data')).filter((f) => /^ch\d+\.json$/.test(f)).sort().map((f) => read(f));
const themes = Object.assign({}, base.vocab.themes, base.phrases.themes, ...chapters.map((c) => c.themes || {}));

function listTable(items, title, intro) {
  let out = `# ${title}\n\n${intro}\n${GEN}\n`;
  for (const [key, name] of Object.entries(themes)) {
    const rows = items.filter((i) => i.t === key);
    if (!rows.length) continue;
    out += `\n## ${name}\n\n| Spanish | English |\n|---|---|\n`;
    for (const r of rows) out += `| ${esc(r.es)} | ${esc(r.en)} |\n`;
  }
  return out;
}

for (const c of chapters) {
  const dir = `chapters/${c.id}`;
  const vocab = [...(c.id === 1 ? base.vocab.items : []), ...(c.vocab || [])];
  const phrases = [...(c.id === 1 ? base.phrases.items : []), ...(c.phrases || [])];
  const verbs = c.verbs || [];
  const drills = new Map((c.drills || []).map((d) => [d.id, d]));
  const dialogues = new Map((c.dialogues || []).map((d) => [d.id, d]));

  write(`${dir}/VOCAB.md`, listTable(vocab, `Chapter ${c.id} vocab (${vocab.length} words)`, 'Nouns come with their article, so you learn the gender with the word. Spain forms first.\n'));
  write(`${dir}/PHRASES.md`, listTable(phrases, `Chapter ${c.id} phrases (${phrases.length})`, 'Whole phrases beat single words. Say them out loud; hear them in the [app](https://coos88.github.io/spanish/).\n'));

  let g = `# Chapter ${c.id} grammar: ${c.title}\n\n${GEN}\n`;
  for (const l of c.lessons || []) {
    g += `\n## ${l.title}\n\n*${l.summary}*\n`;
    for (const card of l.cards) {
      g += `\n${card.rule}\n\n`;
      if (card.examples && card.examples.length) g += '| Spanish | English |\n|---|---|\n' + card.examples.map((e) => `| ${esc(e.es)} | ${esc(e.en)} |\n`).join('');
      if (card.trap) g += `\n> ⚠ ${card.trap}\n`;
      if (card.note) g += `\n> ℹ ${card.note}\n`;
    }
    const d = l.dialogue && dialogues.get(l.dialogue);
    if (d) g += `\n### Dialogue: ${d.title}\n\n` + d.lines.map((x) => `**${x.who}:** ${x.es}  \n*${x.en}*`).join('\n\n') + '\n';
  }
  write(`${dir}/GRAMMAR.md`, g);

  let e = `# Chapter ${c.id} exercises\n\nTry each one on paper first, then open the answers. The app has the same drills with audio: **Learn** tab.\n${GEN}\n`;
  for (const l of c.lessons || []) {
    e += `\n## ${l.title}\n\n`;
    const ds = l.drills.map((id) => drills.get(id)).filter(Boolean);
    ds.forEach((d, i) => { e += `${i + 1}. ${d.prompt.replace(/___/g, "\\_\\_\\_")}${d.hint ? ` *(${d.hint})*` : ''}${d.options ? ` — ${d.options.join(' / ')}` : ''}${d.type === 'build' ? ' *(build the sentence)*' : ''}\n`; });
    e += `\n<details><summary>Answers</summary>\n\n` + ds.map((d, i) => `${i + 1}. ${d.answer.join(' / ')} — ${d.explain}`).join('\n') + '\n\n</details>\n';
  }
  write(`${dir}/EXERCISES.md`, e);

  let r = `# Chapter ${c.id}: ${c.title}\n\n${c.goal}\n\n**At the end you can:**\n${c.canDo.map((x) => `- ${x}`).join('\n')}\n\n`;
  r += `- [Grammar lessons](GRAMMAR.md) (${(c.lessons || []).length} lessons)\n- [Exercises](EXERCISES.md) (${(c.drills || []).length} drills)\n- [Vocab](VOCAB.md) (${vocab.length} words)\n- [Phrases](PHRASES.md) (${phrases.length})\n`;
  if (verbs.length) r += `- New verbs: ${verbs.map((v) => v.inf).join(', ')}\n`;
  r += `\n## Lesson order\n${(c.lessons || []).map((l, i) => `${i + 1}. **${l.title}**: ${l.summary}`).join('\n')}\n`;
  write(`${dir}/README.md`, r);
  console.log(`chapter ${c.id}: ${(c.lessons || []).length} lessons, ${drills.size} drills, ${vocab.length} words, ${phrases.length} phrases`);
}
